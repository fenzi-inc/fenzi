var update = flag.Bool("update", false, "rewrite golden files")

var claude = Agent{
	Name:     "claude",
	Binaries: []string{"/usr/local/lib/node_modules/@anthropic-ai/claude-code/bin/claude.exe"},
	Model:    []ModelEndpoint{{Host: "api.anthropic.com", Port: 443}},
}

func load(t *testing.T, name string) *Document {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("testdata", name))
	if err != nil {
		t.Fatal(err)
	}
	d, err := Parse(raw)
	if err != nil {
		t.Fatal(err)
	}
	return d
}

func golden(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", "golden", name)
	if *update {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run go test ./compiler -update)", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s differs from golden file\n--- got\n%s\n--- want\n%s", name, got, want)
	}
}

func TestGolden(t *testing.T) {
	base := load(t, "default.yaml")
	merged, err := Merge(base, load(t, "project.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	cases := map[string]*Document{
		"default": base,
		"project": merged,
		"review":  load(t, "review.yaml"),
	}
	for name, doc := range cases {
		t.Run(name, func(t *testing.T) {
			target := Target{Agent: claude}
			p, err := Compile(doc, target)
			if err != nil {
				t.Fatal(err)
			}
			out, err := p.YAML("Generated by fenzi from " + name + ". Do not edit.")
			if err != nil {
				t.Fatal(err)
			}
			golden(t, name+".policy.yaml", out)

			b, err := Boundary(doc, target)
			if err != nil {
				t.Fatal(err)
			}
			out, err = b.YAML("Boundary for " + name + ". Generated by fenzi. Do not edit.")
			if err != nil {
				t.Fatal(err)
			}
			golden(t, name+".boundary.yaml", out)
		})
	}
}

func TestCompileChoices(t *testing.T) {
	p, err := Compile(load(t, "default.yaml"), Target{Agent: claude})
	if err != nil {
		t.Fatal(err)
	}
	if p.FilesystemPolicy.IncludeWorkdir {
		t.Error("include_workdir must be false; the prover returns unsupported for workdir-dependent results")
	}
	if p.FilesystemPolicy.ReadWrite[0] != DefaultWorkdir {
		t.Errorf("workdir not listed first in read_write: %v", p.FilesystemPolicy.ReadWrite)
	}
	if p.Landlock.Compatibility != "hard_requirement" {
		t.Errorf("landlock = %q", p.Landlock.Compatibility)
	}
	for key, r := range p.NetworkPolicies {
		if strings.HasPrefix(key, "_provider_") {
			t.Errorf("rule key %q uses the reserved prefix", key)
		}
		for _, e := range r.Endpoints {
			if e.Protocol != "rest" || e.Enforcement != "enforce" {
				t.Errorf("%s: protocol=%q enforcement=%q; every endpoint must be enforced REST", key, e.Protocol, e.Enforcement)
			}
			if e.Access != "" && len(e.Rules) > 0 {
				t.Errorf("%s: an endpoint cannot combine access and rules", key)
			}
		}
	}
	for key, r := range p.NetworkPolicies {
		for _, e := range r.Endpoints {
			if e.AllowEncodedSlash != (e.Access != "" && len(e.Rules) == 0) {
				t.Errorf("%s: allow_encoded_slash only on a preset endpoint, which allows every path", key)
			}
		}
	}
	for key, r := range p.ForProver().NetworkPolicies {
		for _, e := range r.Endpoints {
			if e.AllowEncodedSlash {
				t.Errorf("%s: allow_encoded_slash makes prover 0.1.2 return unsupported", key)
			}
		}
	}
	for _, r := range p.NetworkPolicies {
		for _, e := range r.Endpoints {
			if e.Host == "api.anthropic.com" {
				t.Error("model API must come from the provider, not the candidate policy")
			}
		}
	}
}

