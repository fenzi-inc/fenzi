func TestMerge(t *testing.T) {
	base := load(t, "default.yaml")
	merged, err := Merge(base, load(t, "project.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	var gh *Host
	for i := range merged.Hosts {
		if merged.Hosts[i].Host == "api.github.com" {
			gh = &merged.Hosts[i]
		}
	}
	if gh == nil || gh.Access != AccessReadWrite || len(gh.Allow) != 2 {
		t.Fatalf("project entry should replace the base entry for api.github.com, got %+v", gh)
	}
	if want := len(base.Hosts) + 1; len(merged.Hosts) != want {
		t.Errorf("want %d hosts after merge, got %d", want, len(merged.Hosts))
	}
	if base.Hosts[0].Access != AccessReadOnly {
		t.Error("Merge modified the base document")
	}

	for name, src := range map[string]string{
		"name":      "version: 1\nname: mine\n",
		"agents":    "version: 1\nagents: [claude]\n",
		"approvals": "version: 1\napprovals: auto\n",
	} {
		t.Run(name, func(t *testing.T) {
			p, _ := Parse([]byte(src))
			if _, err := Merge(base, p); err == nil {
				t.Fatalf("project file must not set %s", name)
			}
		})
	}
}

// The compiler must stay testable without a gateway: no process execution and
// no dependency on the CLI packages.
func TestNoGatewayDependency(t *testing.T) {
	files, _ := filepath.Glob("*.go")
	fset := token.NewFileSet()
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		parsed, err := parser.ParseFile(fset, f, nil, parser.ImportsOnly)
		if err != nil {
			t.Fatal(err)
		}
		for _, imp := range parsed.Imports {
			path, _ := strconv.Unquote(imp.Path.Value)
			if path == "os/exec" || strings.HasPrefix(path, "fenzi/") {
				t.Errorf("%s imports %s", f, path)
			}
		}
	}
}
