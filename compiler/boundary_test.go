// A team boundary compiles like a policy, plus the agent's model endpoints.
// The golden file is not paired with a .policy.yaml, so make prove does not
// take it for a recorded pair.
func TestTeamBoundaryGolden(t *testing.T) {
	b, err := TeamBoundary(load(t, "team-boundary.yaml"), Target{Agent: claude})
	if err != nil {
		t.Fatal(err)
	}
	out, err := b.YAML("Team boundary for acme. Generated by fenzi. Do not edit.")
	if err != nil {
		t.Fatal(err)
	}
	golden(t, "team-boundary.yaml", out)
}

// The boundary a policy is proved against is the team's, not one derived
// from the policy: a host the policy lists and the boundary does not is
// missing from the compiled boundary.
func TestTeamBoundaryIsNotDerivedFromThePolicy(t *testing.T) {
	policy := load(t, "default.yaml")
	policy.Hosts = append(policy.Hosts, Host{Host: "paste.example.net", Access: AccessReadOnly})
	target := Target{Agent: claude}
	derived, err := Boundary(policy, target)
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := derived.NetworkPolicies["paste_example_net"]; !ok {
		t.Fatal("the derived boundary should list the policy's own host")
	}
	team, err := TeamBoundary(load(t, "team-boundary.yaml"), target)
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := team.NetworkPolicies["paste_example_net"]; ok {
		t.Fatal("the team boundary took a host from the policy")
	}
	if _, ok := team.NetworkPolicies["model_api_anthropic_com"]; !ok {
		t.Fatal("the team boundary lacks the agent's model endpoint, so the effective policy could never pass")
	}
}

func TestTeamBoundaryRejects(t *testing.T) {
	b := load(t, "team-boundary.yaml")
	grok := claude
	grok.Name = "grok"
	if _, err := TeamBoundary(b, Target{Agent: grok}); !errors.Is(err, ErrNotInBoundary) || !strings.Contains(err.Error(), "grok") {
		t.Errorf("an agent the boundary does not name: %v", err)
	}

	none := load(t, "team-boundary.yaml")
	none.Agents = nil
	if _, err := TeamBoundary(none, Target{Agent: claude}); err == nil || !strings.Contains(err.Error(), "name the agents it covers") {
		t.Errorf("a boundary without agents: %v", err)
	}
	if err := CheckBoundary(nil); err == nil {
		t.Error("a missing boundary passed the check")
	}

	model := load(t, "team-boundary.yaml")
	model.Hosts = append(model.Hosts, Host{Host: "api.anthropic.com", Access: AccessReadOnly})
	if _, err := TeamBoundary(model, Target{Agent: claude}); err == nil || !strings.HasPrefix(err.Error(), "team boundary: hosts: api.anthropic.com:443 is the claude model API") {
		t.Errorf("a boundary listing the model API: %v", err)
	}

	bad := load(t, "team-boundary.yaml")
	bad.Workspace = "everything"
	if _, err := TeamBoundary(bad, Target{Agent: claude}); err == nil || !strings.HasPrefix(err.Error(), "team boundary: invalid policy document") {
		t.Errorf("an invalid boundary: %v", err)
	}
}
