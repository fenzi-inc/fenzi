// ErrNoMCPToken means a server in the policy says it has a token, and none
// is stored on this machine.
type ErrNoMCPToken struct{ Server string }

func (e *ErrNoMCPToken) Error() string {
	return fmt.Sprintf("no token stored for the MCP server %s; run fenzi mcp token %s, or remove token: true from its entry", e.Server, e.Server)
}

// ErrNoMCPSecret means a local server lists a secret, and no value for it
// is stored on this machine.
type ErrNoMCPSecret struct{ Server, Variable string }

func (e *ErrNoMCPSecret) Error() string {
	return fmt.Sprintf("no value stored for %s, which the MCP server %s reads; run fenzi mcp token %s --env %s", e.Variable, e.Server, e.Server, e.Variable)
}

// MCPProviders returns the providers that hold the tokens of the document's
// remote servers and the secrets of its local servers, checking each is
// stored. The policy binds each one to its server's endpoint, or to the
// hosts a local server lists, with credential_binding, so the sandbox sends
// a value to those hosts only.
func MCPProviders(ctx context.Context, oc openshell.Client, d *compiler.Document) ([]string, error) {
	var out []string
	for _, n := range d.MCPNames() {
		s := d.MCP[n]
		if !s.Remote() || !s.Token {
			continue
		}
		name := compiler.MCPProvider(n)
		ok, err := oc.ProviderExists(ctx, name)
		if err != nil {
			return nil, err
		}
		if !ok {
			return nil, &ErrNoMCPToken{Server: n}
		}
		out = append(out, name)
	}
	for _, v := range d.Secrets() {
		name := compiler.SecretProvider(v)
		ok, err := oc.ProviderExists(ctx, name)
		if err != nil {
			return nil, err
		}
		if !ok {
			return nil, &ErrNoMCPSecret{Server: secretUser(d, v), Variable: v}
		}
		out = append(out, name)
	}
	return out, nil
}

// secretUser is the first server, by name, that reads the variable.
func secretUser(d *compiler.Document, variable string) string {
	for _, n := range d.MCPNames() {
		for _, v := range d.MCP[n].Secrets {
			if v == variable {
				return n
			}
		}
	}
	return ""
}

// SecretProfile is the provider profile for one secret of a local server:
// no endpoints, so the value reaches a request only where the sandbox policy
// binds it, and one variable with the name the server reads. Recorded on
// OpenShell 0.1.2: with this profile bound on a REST host, a stdio
// server started by Claude Code saw the placeholder, and the proxy put the
// value in its requests to that host, in a header or the query, and refused
// the placeholder on another host with credential_endpoint_mismatch.
func SecretProfile(variable string) []byte {
	return []byte(fmt.Sprintf(`# Generated by fenzi for the MCP secret %[1]s. Do not edit.
id: %[2]s
display_name: MCP secret %[1]s (Fenzi)
description: %[1]s for local MCP servers, bound to the hosts they list by the sandbox policy
category: other
credentials:
  - name: secret
    description: %[1]s
    env_vars: [%[1]s]
    required: true
    auth_style: bearer
    header_name: authorization
discovery:
  credentials: [secret]
`, variable, compiler.SecretProvider(variable)))
}

// SetMCPSecret stores or replaces a local server's secret, as a provider of
// the variable's own endpointless profile. The value reaches openshell
// through its environment, never its arguments. It reports whether a value
// was replaced.
func SetMCPSecret(ctx context.Context, oc openshell.Client, variable, value string) (bool, error) {
	if strings.TrimSpace(value) == "" {
		return false, fmt.Errorf("the value was empty; nothing stored")
	}
	dir, err := os.MkdirTemp("", "fenzi-mcp-profile-")
	if err != nil {
		return false, err
	}
	defer os.RemoveAll(dir)
	pf := filepath.Join(dir, "profile.yaml")
	if err := os.WriteFile(pf, SecretProfile(variable), 0o600); err != nil {
		return false, err
	}
	id := compiler.SecretProvider(variable)
	if err := oc.EnsureProfile(ctx, id, pf); err != nil {
		return false, err
	}
	exists, err := oc.ProviderExists(ctx, id)
	if err != nil {
		return false, err
	}
	return exists, oc.ProviderSetKey(ctx, id, id, variable, value, exists)
}

// RemoveMCPSecret deletes a stored secret. It refuses while a running
// sandbox was started with it.
func RemoveMCPSecret(ctx context.Context, oc openshell.Client, dirs config.Dirs, variable string) (bool, error) {
	id := compiler.SecretProvider(variable)
	exists, err := oc.ProviderExists(ctx, id)
	if err != nil || !exists {
		return false, err
	}
	running, err := oc.Sandboxes(ctx)
	if err != nil {
		return false, err
	}
	for _, name := range running {
		doc, err := LoadResolved(dirs.Run(name))
		if err != nil {
			continue
		}
		for _, v := range doc.Secrets() {
			if v == variable {
				return false, fmt.Errorf("%s is running with %s; stop it first (fenzi stop %s)", name, variable, name)
			}
		}
	}
	return true, oc.ProviderDelete(ctx, id)
}

// secretSummary is the run line for the secrets local servers get.
func secretSummary(d *compiler.Document) string {
	hosts := map[string][]string{}
	for _, n := range d.MCPNames() {
		s := d.MCP[n]
		for _, v := range s.Secrets {
			for _, h := range s.Hosts {
				if !slices.Contains(hosts[v], h) {
					hosts[v] = append(hosts[v], h)
				}
			}
		}
	}
	var parts []string
	for _, v := range d.Secrets() {
		slices.Sort(hosts[v])
		parts = append(parts, v+" on "+strings.Join(hosts[v], ", "))
	}
	return strings.Join(parts, "; ")
}

// MCPProfile is the provider profile for one server's token: no endpoints of
// its own, so the token reaches a request only where the sandbox policy
// binds it, and one placeholder variable named for the server. Recorded on
// OpenShell 0.1.2: an endpointless profile bound by credential_binding on a
// protocol: mcp endpoint put the real value in that server's requests.
func MCPProfile(server string) []byte {
	id := compiler.MCPProvider(server)
	return []byte(fmt.Sprintf(`# Generated by fenzi for the MCP server %[1]s. Do not edit.
id: %[2]s
display_name: MCP server %[1]s (Fenzi)
description: Token for the MCP server %[1]s, bound to its endpoint by the sandbox policy
category: other
credentials:
  - name: token
    description: Token for %[1]s
    env_vars: [%[3]s]
    required: true
    auth_style: bearer
    header_name: authorization
discovery:
  credentials: [token]
`, server, id, compiler.MCPTokenEnv(server)))
}

// agentMCPFiles are the agents' own MCP config files in a project. The agent
// in the sandbox does not load them, since Fenzi passes its own list, but
// they are copied with the project, and a server's env or headers there
// often hold a token in plain text.
var agentMCPFiles = []string{".mcp.json", ".cursor/mcp.json", ".vscode/mcp.json", "opencode.json"}

// MCPConfigSecrets lists the agents' MCP config files about to be copied
// whose env, environment or headers hold a value that looks like a secret,
// each with the names that hold one. A reference such as ${VAR} or
// {env:VAR} is not a value.
func MCPConfigSecrets(repo string, m workspace.Manifest) []string {
	var out []string
	for _, rel := range agentMCPFiles {
		if _, ok := m[rel]; !ok {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(repo, filepath.FromSlash(rel)))
		if err != nil {
			continue
		}
		var doc any
		if json.Unmarshal(raw, &doc) != nil {
			continue
		}
		var names []string
		findSecrets(doc, "", &names)
		if len(names) > 0 {
			slices.Sort(names)
			names = slices.Compact(names)
			out = append(out, rel+" (holds "+strings.Join(names, ", ")+")")
		}
	}
	return out
}

func findSecrets(v any, parent string, names *[]string) {
	switch x := v.(type) {
	case map[string]any:
		for k, c := range x {
			if s, ok := c.(string); ok && (parent == "env" || parent == "environment" || parent == "headers") {
				ref := strings.HasPrefix(s, "${") || strings.HasPrefix(s, "{env:") || strings.HasPrefix(s, "Bearer ${") || strings.HasPrefix(s, "Bearer {env:")
				if !ref && (compiler.SecretEnv(strings.ToUpper(strings.ReplaceAll(k, "-", "_")), s) || strings.EqualFold(k, "authorization")) {
					*names = append(*names, k)
				}
				continue
			}
			findSecrets(c, k, names)
		}
	case []any:
		for _, c := range x {
			findSecrets(c, parent, names)
		}
	}
}

// mcpSummary is the run line for the servers the agent gets.
func mcpSummary(d *compiler.Document, agent string) string {
	var parts []string
	for _, n := range d.MCPNames() {
		s := d.MCP[n]
		switch {
		case !s.For(agent):
			continue
		case s.Connectors() && s.Tools.AllowsAll():
			parts = append(parts, n+" (account connectors, all tools)")
		case s.Connectors():
			parts = append(parts, fmt.Sprintf("%s (account connectors, %s)", n, plural(len(s.Tools.Allow), "tool")))
		case !s.Remote():
			parts = append(parts, n+" (local)")
		case s.Tools.AllowsAll():
			parts = append(parts, n+" (all tools)")
		default:
			parts = append(parts, fmt.Sprintf("%s (%s)", n, plural(len(s.Tools.Allow), "tool")))
		}
	}
	return strings.Join(parts, ", ")
}

// writeFiles puts files into the sandbox with the image's python3, the way
// the request guide is written. Each must be under the workdir.
func writeFiles(ctx context.Context, d Deps, sandbox string, files []agents.File) error {
	for _, f := range files {
		dest := path.Clean(f.Path)
		if !strings.HasPrefix(dest, compiler.DefaultWorkdir+"/") {
			return fmt.Errorf("file %q is outside the sandbox workdir", dest)
		}
		script := "import base64, pathlib\n" +
			"p = pathlib.Path(" + strconv.Quote(dest) + ")\n" +
			"p.parent.mkdir(parents=True, exist_ok=True)\n" +
			"p.write_bytes(base64.b64decode(" + strconv.Quote(base64.StdEncoding.EncodeToString([]byte(f.Content))) + "))\n"
		if _, err := d.OpenShell.ExecOutput(ctx, sandbox, "python3", "-c", script); err != nil {
			return fmt.Errorf("writing %s: %w", dest, err)
		}
	}
	return nil
}

func plural(n int, word string) string {
	if n == 1 {
		return "1 " + word
	}
	return strconv.Itoa(n) + " " + word + "s"
}

