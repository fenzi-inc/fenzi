// ErrNoMCPToken means a server in the policy says it has a token, and none
// is stored on this machine.
type ErrNoMCPToken struct{ Server string }

func (e *ErrNoMCPToken) Error() string {
	return fmt.Sprintf("no token stored for the MCP server %s; run fenzi mcp token %s, or remove token: true from its entry", e.Server, e.Server)
}

// MCPProviders returns the providers that hold the tokens of the document's
// remote servers, checking each is stored. The policy binds each one to its
// server's endpoint with credential_binding, so the sandbox sends a token to
// its own server only.
func MCPProviders(ctx context.Context, oc openshell.Client, d *compiler.Document) ([]string, error) {
	var out []string
	for _, n := range d.MCPNames() {
		s := d.MCP[n]
		if !s.Remote() || !s.Token {
			continue
		}
		name := compiler.MCPProvider(n)
		ok, err := oc.ProviderExists(ctx, name)
		if err != nil {
			return nil, err
		}
		if !ok {
			return nil, &ErrNoMCPToken{Server: n}
		}
		out = append(out, name)
	}
	return out, nil
}

// MCPProfile is the provider profile for one server's token: no endpoints of
// its own, so the token reaches a request only where the sandbox policy
// binds it, and one placeholder variable named for the server. Recorded on
// OpenShell 0.1.2: an endpointless profile bound by credential_binding on a
// protocol: mcp endpoint put the real value in that server's requests.
func MCPProfile(server string) []byte {
	id := compiler.MCPProvider(server)
	return []byte(fmt.Sprintf(`# Generated by fenzi for the MCP server %[1]s. Do not edit.
id: %[2]s
display_name: MCP server %[1]s (Fenzi)
description: Token for the MCP server %[1]s, bound to its endpoint by the sandbox policy
category: other
credentials:
  - name: token
    description: Token for %[1]s
    env_vars: [%[3]s]
    required: true
    auth_style: bearer
    header_name: authorization
discovery:
  credentials: [token]
`, server, id, compiler.MCPTokenEnv(server)))
}

// mcpSummary is the run line for the servers the agent gets.
func mcpSummary(d *compiler.Document) string {
	var parts []string
	for _, n := range d.MCPNames() {
		s := d.MCP[n]
		switch {
		case !s.Remote():
			parts = append(parts, n+" (local)")
		case s.Tools.AllowsAll():
			parts = append(parts, n+" (all tools)")
		default:
			parts = append(parts, fmt.Sprintf("%s (%s)", n, plural(len(s.Tools.Allow), "tool")))
		}
	}
	return strings.Join(parts, ", ")
}

// writeFiles puts files into the sandbox with the image's python3, the way
// the request guide is written. Each must be under the workdir.
func writeFiles(ctx context.Context, d Deps, sandbox string, files []agents.File) error {
	for _, f := range files {
		dest := path.Clean(f.Path)
		if !strings.HasPrefix(dest, compiler.DefaultWorkdir+"/") {
			return fmt.Errorf("file %q is outside the sandbox workdir", dest)
		}
		script := "import base64, pathlib\n" +
			"p = pathlib.Path(" + strconv.Quote(dest) + ")\n" +
			"p.parent.mkdir(parents=True, exist_ok=True)\n" +
			"p.write_bytes(base64.b64decode(" + strconv.Quote(base64.StdEncoding.EncodeToString([]byte(f.Content))) + "))\n"
		if _, err := d.OpenShell.ExecOutput(ctx, sandbox, "python3", "-c", script); err != nil {
			return fmt.Errorf("writing %s: %w", dest, err)
		}
	}
	return nil
}

func plural(n int, word string) string {
	if n == 1 {
		return "1 " + word
	}
	return strconv.Itoa(n) + " " + word + "s"
}

// SetMCPToken stores or replaces the token of an MCP server, as a provider
// of the server's own endpointless profile. The value reaches openshell
// through its environment, never its arguments. It reports whether a token
// was replaced.
func SetMCPToken(ctx context.Context, oc openshell.Client, server, value string) (bool, error) {
	if strings.TrimSpace(value) == "" {
		return false, fmt.Errorf("the token was empty; nothing stored")
	}
	dir, err := os.MkdirTemp("", "fenzi-mcp-profile-")
	if err != nil {
		return false, err
	}
	defer os.RemoveAll(dir)
	pf := filepath.Join(dir, "profile.yaml")
	if err := os.WriteFile(pf, MCPProfile(server), 0o600); err != nil {
		return false, err
	}
	id := compiler.MCPProvider(server)
	if err := oc.EnsureProfile(ctx, id, pf); err != nil {
		return false, err
	}
	exists, err := oc.ProviderExists(ctx, id)
	if err != nil {
		return false, err
	}
	return exists, oc.ProviderSetKey(ctx, id, id, compiler.MCPTokenEnv(server), value, exists)
}

// RemoveMCPToken deletes a server's token. Like a model key, it refuses
// while a running sandbox was started with it.
func RemoveMCPToken(ctx context.Context, oc openshell.Client, dirs config.Dirs, server string) (bool, error) {
	id := compiler.MCPProvider(server)
	exists, err := oc.ProviderExists(ctx, id)
	if err != nil || !exists {
		return false, err
	}
	running, err := oc.Sandboxes(ctx)
	if err != nil {
		return false, err
	}
	for _, name := range running {
		doc, err := LoadResolved(dirs.Run(name))
		if err != nil {
			continue
		}
		if s, ok := doc.MCP[server]; ok && s.Token {
			return false, fmt.Errorf("%s is running with the %s token; stop it first (fenzi stop %s)", name, server, name)
		}
	}
	return true, oc.ProviderDelete(ctx, id)
}
